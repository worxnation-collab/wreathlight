export function fmtDate(iso: string, lang: Lang, opts: Intl.DateTimeFormatOptions = { month: "short", day: "numeric" }): string {
  return new Intl.DateTimeFormat(lang === "es" ? "es-US" : "en-US", { ...opts, timeZone: "UTC" }).format(new Date(iso.slice(0, 10) + "T12:00:00Z"));
}
